#!/usr/bin/env python3
"""Generate the n8n workflow JSON files from the tested modules in src/.

Source of truth is src/*.js (unit-tested). n8n Code nodes cannot import local files, so each
Code node embeds a bundle of those modules below its own few lines of logic. Never edit the
generated workflows/*.json by hand: edit src/ and run `python3 scripts/build_workflows.py`.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "src"
OUT = ROOT / "workflows"
MODULES = ["lib", "pipeline", "telegram", "store", "mailer", "agent"]  # dependency order

ENV_KEYS = [
    "TAVILY_API_KEY", "SERPER_API_KEY", "HUNTER_API_KEY", "GEMINI_API_KEY", "GEMINI_MODEL_PRIMARY",
    "GEMINI_MODEL_FALLBACK", "GEMINI_MODEL_FALLBACK2", "TELEGRAM_BOT_TOKEN", "TELEGRAM_ALLOWED_CHAT_IDS",
    "STORE_BACKEND", "MAIL_BACKEND", "DATA_DIR", "GOOGLE_SHEET_ID", "GOOGLE_SERVICE_ACCOUNT_B64",
    "GMAIL_CLIENT_ID", "GMAIL_CLIENT_SECRET", "GMAIL_REFRESH_TOKEN", "SANDBOX_MODE", "SANDBOX_INBOX",
    "ALLOW_REAL_SEND", "SEND_ALLOWLIST", "FOLLOWUP_DELAY_MINUTES", "REQUIRE_APPROVAL",
]

HEADER = "// GENERATED by scripts/build_workflows.py from src/*.js. Edit src/, not this node.\n"


def strip(js: str) -> str:
    """Drop whole-line comments and blank lines to keep the embedded bundle small."""
    return "\n".join(l for l in js.splitlines() if l.strip() and not l.lstrip().startswith("//"))


def bundle() -> str:
    parts = [
        "const __m = {};",
        "const __def = (name, fn) => { const module = { exports: {} }; "
        "fn(module, (n) => __m[String(n).replace(/^\\.\\//, '').replace(/\\.js$/, '')] || require(n)); __m[name] = module.exports; };",
    ]
    for name in MODULES:
        parts.append(f"__def('{name}', function (module, require) {{\n{strip((SRC / (name + '.js')).read_text())}\n}});")
    return "\n".join(parts)


PRELUDE = """
const __env = {};
for (const k of %s) { try { if ($env[k] !== undefined) __env[k] = $env[k]; } catch (e) {} }
const __helpers = this.helpers;
const __http = async ({ method = 'GET', url, headers = {}, body, timeoutMs = 20000 }) => {
  const o = { method, url, headers: { ...headers }, timeout: timeoutMs, returnFullResponse: true, ignoreHttpStatusCodes: true, encoding: 'text', json: false };
  if (body !== undefined) { if (typeof body === 'string') o.body = body; else { o.body = JSON.stringify(body); if (!o.headers['Content-Type']) o.headers['Content-Type'] = 'application/json'; } }
  const r = await __helpers.httpRequest(o);
  const text = typeof r.body === 'string' ? r.body : (r.body == null ? '' : (typeof r.body === 'object' ? JSON.stringify(r.body) : String(r.body)));
  let json; try { json = JSON.parse(text); } catch (e) { json = undefined; }
  return { status: r.statusCode, json, text };
};
const A = __m.agent, T = __m.telegram;
const ctx = A.makeCtx({ http: __http, env: __env, fs: require('fs'), crypto: require('crypto'), sleep: (ms) => new Promise((r) => setTimeout(r, ms)) });
""" % json.dumps(ENV_KEYS)


def code_node(name: str, body: str, pos, doc: str = "") -> dict:
    js = HEADER + (f"// {doc}\n" if doc else "") + f"async function main() {{\n{body.strip()}\n}}\n" + "\n".join([bundle(), PRELUDE.strip()]) + "\nreturn await main();\n"
    return {"parameters": {"mode": "runOnceForAllItems", "language": "javaScript", "jsCode": js},
            "name": name, "type": "n8n-nodes-base.code", "typeVersion": 2, "position": pos}


def schedule(name, pos, **interval):
    field, n = next(iter(interval.items()))
    return {"parameters": {"rule": {"interval": [{"field": field, f"{field}Interval": n}]}}, "name": name,
            "type": "n8n-nodes-base.scheduleTrigger", "typeVersion": 1.2, "position": pos}


def manual(pos):
    return {"parameters": {}, "name": "Run once (manual)", "type": "n8n-nodes-base.manualTrigger", "typeVersion": 1, "position": pos}


def note(text, pos, w=420, h=200, color=4):
    return {"parameters": {"content": text, "height": h, "width": w, "color": color}, "name": f"Note {pos[0]}x{pos[1]}",
            "type": "n8n-nodes-base.stickyNote", "typeVersion": 1, "position": pos}


def connect(chain, extra_sources=None):
    conns = {}
    for a, b in zip(chain, chain[1:]):
        conns.setdefault(a, {"main": [[]]})["main"][0].append({"node": b, "type": "main", "index": 0})
    for src, dst in (extra_sources or []):
        conns.setdefault(src, {"main": [[]]})["main"][0].append({"node": dst, "type": "main", "index": 0})
    return conns


def workflow(wid, name, nodes, conns, error_wf=None):
    settings = {"executionOrder": "v1"}
    if error_wf:
        settings["errorWorkflow"] = error_wf
    return {"id": wid, "name": name, "active": False, "nodes": nodes, "connections": conns, "settings": settings,
            "pinData": {}, "tags": [], "meta": {"generatedBy": "scripts/build_workflows.py"}}


ERR_ID = "bdrerrors0000001"

# ---------------------------------------------------------------- 1. Telegram intake
def wf_intake():
    nodes = [
        schedule("Every 20 seconds", [0, 200], seconds=20),
        manual([0, 380]),
        code_node("Poll Telegram", "const items = await A.pollTelegram(ctx);\nreturn items.map((json) => ({ json }));", [260, 280],
                  "Fetch new Telegram messages since the stored offset. Nothing is marked as read yet."),
        code_node("Handle commands & queue leads", """
const replies = await A.handleMessages(ctx, $input.all().map((i) => i.json));
return replies.map((json) => ({ json }));""", [520, 280],
                  "Authorise the chat, parse 'Find event leads for X in Y', de-duplicate, add a NEW row, then commit the offset."),
        code_node("Send replies", """
let sent = 0;
for (const i of $input.all()) { if (await T.deliver(ctx, i.json)) sent++; }
return [{ json: { sent } }];""", [780, 280], "Reply in Telegram. The bot token never appears in the n8n UI."),
        note("**01 Telegram intake**\nPolls the bot every 20 s (no public URL / webhook needed).\n`Find event leads for Zomato in Gurgaon` -> row with status NEW in the Leads table. The processor workflow does the rest.\nUnknown chats are refused.", [0, 0], 520, 170),
    ]
    chain = ["Every 20 seconds", "Poll Telegram", "Handle commands & queue leads", "Send replies"]
    conns = connect(chain, [("Run once (manual)", "Poll Telegram")])
    return workflow("bdrintake0000001", "BDR 01 - Telegram intake", nodes, conns, ERR_ID)


# ---------------------------------------------------------------- 2. Lead processor
def wf_processor():
    nodes = [
        schedule("Every minute", [0, 200], minutes=1),
        manual([0, 380]),
        code_node("Claim leads", "const claimed = await A.claimLeads(ctx, 2);\nreturn claimed.map((c) => ({ json: c }));", [260, 280],
                  "Adopt hand-typed Sheet rows, mark duplicates, recover stuck rows, claim up to 2 leads (status -> PROCESSING)."),
        code_node("Enrich & write pitch", """
const out = [];
for (const i of $input.all()) out.push({ json: await A.enrichItem(ctx, i.json) });
return out;""", [520, 280], "Find company site -> find Founder/HR/Events person -> find email -> Gemini writes the 3-line pitch. Every claim is verified in code."),
        code_node("Save to Sheet & send outreach", """
const out = [];
for (const i of $input.all()) out.push({ json: await A.saveAndSend(ctx, i.json) });
return out;""", [780, 280], "Write results + activity log back to the Sheet, then send the outreach (sandbox inbox unless explicitly allowed) and schedule the follow-up."),
        code_node("Notify on Telegram", """
let sent = 0;
for (const i of $input.all()) { const r = i.json; if (r.chat_id && r.text && await T.deliver(ctx, r)) sent++; }
return [{ json: { sent } }];""", [1040, 280], "Send the result card to whoever asked (or the admin chat for Sheet-added rows)."),
        note("**02 Lead processor** (the brain)\nThe Sheet's `status` column is the queue: NEW -> PROCESSING -> READY_TO_SEND / NEEDS_REVIEW / NOT_FOUND -> SENT.\nSafe to run every minute: claimed rows are locked, stuck rows are recovered, failures retry up to 3 times.", [0, 0], 560, 170),
    ]
    chain = ["Every minute", "Claim leads", "Enrich & write pitch", "Save to Sheet & send outreach", "Notify on Telegram"]
    return workflow("bdrprocess0000001", "BDR 02 - Lead processor", nodes, connect(chain, [("Run once (manual)", "Claim leads")]), ERR_ID)


# ---------------------------------------------------------------- 3. Follow-up scheduler
def wf_followup():
    nodes = [
        schedule("Every minute", [0, 200], minutes=1),
        manual([0, 380]),
        code_node("Find due follow-ups", "const due = await A.dueFollowups(ctx, 5);\nreturn due.map((d) => ({ json: d }));", [260, 280],
                  "Rows with status SENT whose follow-up time has passed and no follow-up sent yet."),
        code_node("Check for reply, else follow up", """
const out = [];
for (const i of $input.all()) out.push({ json: await A.runFollowup(ctx, i.json) });
return out;""", [520, 280], "If the lead replied: status REPLIED and stop. If we cannot tell: do nothing and retry. Otherwise send the follow-up in the same thread."),
        code_node("Notify on Telegram", """
let sent = 0;
for (const i of $input.all()) { const r = i.json; if (r.chat_id && r.text && await T.deliver(ctx, r)) sent++; }
return [{ json: { sent } }];""", [780, 280]),
        note("**03 Follow-up scheduler**\nNo long-lived 'Wait' nodes (they hold an execution open for days and die on restart). The Sheet holds the due time; this workflow just scans it.", [0, 0], 520, 140),
    ]
    chain = ["Every minute", "Find due follow-ups", "Check for reply, else follow up", "Notify on Telegram"]
    return workflow("bdrfollowup000001", "BDR 03 - Follow-up scheduler", nodes, connect(chain, [("Run once (manual)", "Find due follow-ups")]), ERR_ID)


# ---------------------------------------------------------------- 4. Error handler
def wf_errors():
    nodes = [
        {"parameters": {}, "name": "On workflow error", "type": "n8n-nodes-base.errorTrigger", "typeVersion": 1, "position": [0, 200]},
        code_node("Alert admin on Telegram", """
const e = $input.first().json;
const wf = (e.workflow && e.workflow.name) || 'unknown';
const node = (e.execution && e.execution.lastNodeExecuted) || 'unknown';
const msg = (e.execution && e.execution.error && e.execution.error.message) || 'no message';
const admin = A.adminChat(ctx);
if (admin) await T.sendMessage(ctx, admin, A.errorText(wf, node, msg));
return [{ json: { alerted: !!admin } }];""", [260, 200], "Any failure in workflows 01-03 lands here and pings the admin chat."),
    ]
    return workflow(ERR_ID, "BDR 99 - Error alerts", nodes, connect(["On workflow error", "Alert admin on Telegram"]))


def main():
    OUT.mkdir(exist_ok=True)
    for old in OUT.glob("*.json"):
        old.unlink()
    files = {"01_telegram_intake.json": wf_intake(), "02_lead_processor.json": wf_processor(),
             "03_followup_scheduler.json": wf_followup(), "99_error_alerts.json": wf_errors()}
    for fname, wf in files.items():
        (OUT / fname).write_text(json.dumps(wf, indent=2, ensure_ascii=False) + "\n")
        print(f"wrote workflows/{fname}  ({(OUT / fname).stat().st_size // 1024} KB, {len(wf['nodes'])} nodes)")


if __name__ == "__main__":
    main()

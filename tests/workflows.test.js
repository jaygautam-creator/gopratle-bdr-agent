// Guards on the generated n8n workflows and the Sheet templates, so neither can drift from src/.
const assert = require('node:assert/strict');
const test = require('node:test');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { execFileSync } = require('node:child_process');
const S = require('../src/store.js');

const root = path.join(__dirname, '..');
const wfDir = path.join(root, 'workflows');
const files = fs.readdirSync(wfDir).filter((f) => f.endsWith('.json'));

test('there are four workflows', () => assert.deepEqual(files.sort(), ['01_telegram_intake.json', '02_lead_processor.json', '03_followup_scheduler.json', '99_error_alerts.json']));

for (const f of files) {
  const wf = JSON.parse(fs.readFileSync(path.join(wfDir, f), 'utf8'));
  test(`${f}: connections reference real nodes and every code node compiles`, () => {
    const names = new Set(wf.nodes.map((n) => n.name));
    for (const [src, c] of Object.entries(wf.connections)) {
      assert.ok(names.has(src), 'unknown source ' + src);
      for (const out of c.main) for (const t of out) assert.ok(names.has(t.node), 'unknown target ' + t.node);
    }
    for (const n of wf.nodes.filter((x) => x.type === 'n8n-nodes-base.code')) {
      new vm.Script('(async function(){' + n.parameters.jsCode + '\n})', { filename: wf.name + '/' + n.name }); // throws on syntax errors
      assert.match(n.parameters.jsCode, /^\/\/ GENERATED by/);
    }
  });
  test(`${f}: no secret values are embedded`, () => {
    const text = fs.readFileSync(path.join(wfDir, f), 'utf8');
    const env = fs.existsSync(path.join(root, '.env')) ? fs.readFileSync(path.join(root, '.env'), 'utf8') : '';
    for (const m of env.matchAll(/^(?:[A-Z_]*(?:KEY|TOKEN|SECRET|B64))=(.{12,})$/gm)) assert.ok(!text.includes(m[1].trim()), 'a secret from .env leaked into ' + f);
  });
}

test('workflows are up to date with src/ (run: python3 scripts/build_workflows.py)', () => {
  const before = files.map((f) => fs.readFileSync(path.join(wfDir, f), 'utf8'));
  execFileSync('python3', ['-I', path.join(root, 'scripts', 'build_workflows.py')], { stdio: 'pipe' });
  const after = files.map((f) => fs.readFileSync(path.join(wfDir, f), 'utf8'));
  assert.deepEqual(after.map((x) => x.length), before.map((x) => x.length));
  assert.ok(after.every((x, i) => x === before[i]), 'generated workflows were stale; they have been regenerated, commit them');
});

test('Sheet CSV templates match the columns the code uses', () => {
  const head = (f) => fs.readFileSync(path.join(root, 'sheet', f), 'utf8').split('\n')[0].trim();
  assert.equal(head('Leads.csv'), S.COLS.join(','));
  assert.equal(head('Activity_log.csv'), 'timestamp,request_id,step,level,message');
  assert.equal(head('Config.csv'), 'key,value,description');
  const keys = fs.readFileSync(path.join(root, 'sheet', 'Config.csv'), 'utf8').split('\n').slice(1).filter(Boolean).map((l) => l.split(',')[0]);
  for (const k of Object.keys(S.DEFAULT_CONFIG)) assert.ok(keys.includes(k), 'Config.csv lacks ' + k);
});

test('docker-compose passes every env var the workflows read', () => {
  const compose = fs.readFileSync(path.join(root, 'docker-compose.yml'), 'utf8');
  const py = fs.readFileSync(path.join(root, 'scripts', 'build_workflows.py'), 'utf8');
  const keys = [...py.slice(py.indexOf('ENV_KEYS = ['), py.indexOf(']', py.indexOf('ENV_KEYS = ['))).matchAll(/"([A-Z0-9_]+)"/g)].map((m) => m[1]);
  for (const k of keys) assert.ok(new RegExp('^\\s+- ' + k + '\\s*$', 'm').test(compose), k + ' is not passed through docker-compose.yml');
});
